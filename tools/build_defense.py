"""Generate presentation notes from actual output; demo IDs never affect analysis."""
import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def main():
    df = pd.read_parquet(ROOT / 'output/node_metrics.parquet').sort_values(['priority_score', 'gid'], ascending=[False, True])
    df['rank'] = range(1, len(df)+1)
    df = df.set_index('gid')
    report = json.loads((ROOT / 'output/run_report.json').read_text(encoding='utf-8'))
    checks = [s for s in report['ranking_sensitivity'] if s['scenario'] not in ('baseline', 'without_role')]
    overlap = min(s['top_overlap'] for s in checks)
    notes = [
        '# Защита проекта Граф денег',
        '',
        '## Сценарий на пять минут',
        '',
        '0:00–0:35 — задача. Из исходных переводов строим объяснимую очередь ручной проверки. Покажите architecture.svg: данные → метрики → роли → интерфейс.',
        '',
        '0:35–1:00 — живой запуск `.\\run.bat`. Откройте `output/graph.html`: 2248 узлов, 3119 рёбер, 105 кластеров. Все вычисления и интерфейс локальны.',
        '',
        '1:00–3:30 — найдите три gid ниже. Покажите фактические потоки, правило роли, вклад в приоритет и путь от seed. Слева топ остаётся доступным.',
        '',
        f'3:30–4:10 — кластер и устойчивость. Выберите кластер, прочитайте внутреннюю долю, вход/выход, основных получателей. При отдельных изменениях весов ±20% сохраняется минимум {overlap}/30 участников топа. Перестановки внутри топа возможны.',
        '',
        '4:10–5:00 — ограничения и результат. Покажите лист depth=4 и оговорку об обрыве, затем «Вся сеть». Предлагаем проверяемые гипотезы и список дополнительных данных, а не установленную организационную структуру.',
        '',
        f'Последний расчёт: {report["elapsed_seconds"]:.3f} с внутри пайплайна. Установка и старт Python не входят в этот замер. Версии и хеши входов в `run_report.json`.',
        '', '## Три примера', '',
    ]
    cases = [
        (100000002578405100, 'Веерное распределение', '116 получателей — самостоятельный структурный признак. Временная доля ниже 50% теперь не убирает роль. Выход больше наблюдаемого входа: нужны полные входящие выписки.'),
        (100000002398779100, 'Сбор с малым дальнейшим выходом', 'Много плательщиков и около 6% дальнейшего выхода. Это основание проверить консолидацию; начальный остаток и внешние переводы неизвестны.'),
        (100000008165763100, 'Кандидат на координацию', 'Помимо активности есть несколько близких seed и входных ветвей. Пути могут иметь общих предков; роль остаётся гипотезой. Высокий оборот сам по себе больше не даёт эту роль.'),
    ]
    for gid, title, explanation in cases:
        row = df.loc[gid]
        path = ' → '.join(row.seed_path)
        notes += [f'### {title}', '', f'**gid `{gid}` · {row.role} · место {row["rank"]} · диапазон {row.rank_min}–{row.rank_max}**', '',
                  f'Вход: {row.sum_in:,.0f} KZT от {row.fan_in} плательщиков. Выход: {row.sum_out:,.0f} KZT к {row.fan_out} получателям. Выход/вход: {row.pass_through_ratio:.2%}. Временная доля: {row.rapid_out_share:.2%}.', '',
                  f'Seed за ≤2 шага: {row.near_seed_count}; за ≤4: {row.reachable_seed_count}; входных ветвей: {row.seed_branch_count}.', '',
                  f'Путь: `{path}`. Наличие рёбер не устанавливает временной порядок переводов.', '', explanation, '',
                  f'Кластер {row.cluster_id}; приоритет {row.priority_score:.4f}; evidence: {row.evidence}.', '']
    notes += ['## Ответы на вопросы жюри', '',
              '- **Почему не accuracy?** Нет размеченных ролей. Проверены контракты, граничные случаи, воспроизводимость и устойчивость ранжирования. Они не заменяют экспертную валидацию.',
              '- **Почему 35 компонент вместо 16?** 16 с рёбрами плюс 19 изолированных узлов; все узлы сохранены.',
              '- **Почему terminal на глубине 4?** Используем метку из словаря ТЗ с ограничениями: сила правила 0,25, явное предупреждение, нулевой вклад «сбор с малой отдачей». Оседание денег не утверждается.',
              '- **Что изменили после проверки?** Структурный distributor, более узкий coordinator, шестикомпонентный приоритет, 14 сценариев весов, содержательные потоки кластеров, постоянный топ, пути, офлайн-запуск.',
              '- **Почему не LLM?** Основные вопросы решаются проверяемыми расчётами. Внешние источники, дополнительные атрибуты клиентов и облачные API не используются.',
              '- **Какие данные запросить дальше?** Полные входящие/исходящие выписки, точные временные метки, начальные остатки и назначения платежей. Запрос и решения выполняет аналитик.',
              '- **Масштаб до миллиона?** Колонночный движок, CSR/компилируемый граф, ограниченное распространение seed-контекста и подграфы через API. Подробности в README.', '',
              '## Перед демонстрацией', '',
              'Проверьте Python 3.12 x64, распакуйте офлайн-комплект с wheelhouse, запустите run.bat, откройте graph.html и architecture.svg. На защите повторите пересчёт. Не переносите старый .venv. Архив содержит данные хакатона и предназначен для передачи в его рамках.', '']
    (ROOT / 'docs').mkdir(exist_ok=True)
    (ROOT / 'docs/defense.md').write_text('\n'.join(notes), encoding='utf-8')


if __name__ == '__main__':
    main()

